const BRIDGE_FILE: &str = {
	const HEAD: &[u8; 3] = b"cpp";
	const TAIL: &[u8; 10] = b"bridge.hpp";

	const BRIDGE_FILE_BYTES: [u8; HEAD.len() + MAIN_SEPARATOR_STR.len() + TAIL.len()] = {
		let mut bytes = [0u8; _];
		let (head, tail) = bytes.split_at_mut(HEAD.len());
		let (sep, tail) = tail.split_at_mut(MAIN_SEPARATOR_STR.len());

		head.copy_from_slice(HEAD);
		sep.copy_from_slice(MAIN_SEPARATOR_STR.as_bytes());
		tail.copy_from_slice(TAIL);
		bytes
	};

	let Ok(_str) = str::from_utf8(&BRIDGE_FILE_BYTES) else {
		panic!()
	};

	"bridge.hpp"
};

