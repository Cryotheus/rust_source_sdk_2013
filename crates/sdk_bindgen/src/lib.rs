#[derive(Debug)]
pub struct GeneratedBindings {
	files: BTreeMap<PathBuf, String>,
	included_files: Vec<PathBuf>,
}

impl GeneratedBindings {
	/// Returns a self-contained inline module tree as Rust tokens.
	///
	/// [`Self::write`] still emits the same bindings as separate files. Use
	/// [`Self::root_source`] when only that split tree's root `mod.rs` is needed.
	pub fn to_token_stream(&self) -> TokenStream {
		let syntax = inline_generated_tree(&self.files)
			.expect("the generated module tree was already parsed and validated");

		quote::quote!(#syntax)
	}

	/// Renders a self-contained inline module tree as readable Rust source.
	pub fn to_source(&self) -> String {
		prettyplease::unparse(
			&inline_generated_tree(&self.files)
				.expect("the generated module tree was already parsed and validated"),
		)
	}

	/// Returns the root `mod.rs` for the split, filesystem-backed module tree.
	pub fn root_source(&self) -> &str {
		self.files
			.get(Path::new("mod.rs"))
			.map(String::as_str)
			.expect("generated bindings always contain mod.rs")
	}

	/// All generated files, keyed by their path relative to the output folder.
	pub fn files(&self) -> &BTreeMap<PathBuf, String> {
		&self.files
	}

	/// Headers observed while parsing the final translation unit.
	pub fn included_files(&self) -> &[PathBuf] {
		&self.included_files
	}

	/// Writes the split tree and removes stale files owned by an earlier write.
	/// Files not listed in the generator manifest are never removed.
	pub fn write(&self, path: impl AsRef<Path>) -> Result<(), std::io::Error> {
		let root = path.as_ref();

		fs::create_dir_all(root)?;

		let desired = self
			.files
			.keys()
			.map(|path| Ok((generated_path_key(path)?, path)))
			.collect::<Result<BTreeMap<_, _>, std::io::Error>>()?;

		let manifest_path = root.join(GENERATED_FILES_MANIFEST);

		let previous = match fs::read_to_string(&manifest_path) {
			Ok(manifest) => manifest
				.lines()
				.filter(|line| !line.is_empty() && !line.starts_with('#'))
				.map(generated_path_from_key)
				.collect::<Result<Vec<_>, _>>()?,

			Err(error) if error.kind() == std::io::ErrorKind::NotFound => Vec::new(),
			Err(error) => return Err(error),
		};

		for stale in previous {
			if desired.contains_key(&generated_path_key(&stale)?) {
				continue;
			}

			match fs::remove_file(root.join(stale)) {
				Ok(()) => {}
				Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
				Err(error) => return Err(error),
			}
		}

		for (relative, contents) in &self.files {
			let output = root.join(relative);

			if let Some(parent) = output.parent() {
				fs::create_dir_all(parent)?;
			}

			fs::write(output, contents)?;
		}

		let mut manifest = String::from(GENERATED_MANIFEST_HEADER);

		manifest.push_str(&desired.keys().cloned().collect::<Vec<_>>().join("\n"));
		manifest.push('\n');
		fs::write(manifest_path, manifest)?;

		Ok(())
	}
}

/// All targets supported by this crate as of now.
#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub enum SupportedTarget {
	/// `i686-unknown-linux-gnu`
	Linux32,

	/// `x86_64-unknown-linux-gnu`
	Linux64,

	/// `i686-pc-windows-msvc`
	Windows32,

	/// `x86_64-pc-windows-msvc`
	Windows64,
}

impl SupportedTarget {
	pub fn from_env() -> anyhow::Result<Self> {
		Self::from_parts(
			&cargo_var("CARGO_CFG_TARGET_ARCH")?,
			&cargo_var("CARGO_CFG_TARGET_OS")?,
			&cargo_var("CARGO_CFG_TARGET_ENV")?,
		)
		.map_err(Into::into)
	}

	pub const fn from_parts(arch: &str, os: &str, env: &str) -> Result<Self, TargetSupportError> {
		// HACK: cannot match `str` in `const` yet, so use `as_bytes`.
		match [arch.as_bytes(), os.as_bytes(), env.as_bytes()] {
			[b"i686", b"linux", b"gnu"] => Ok(Self::Linux32),
			[b"x86_64", b"linux", b"gnu"] => Ok(Self::Linux64),
			[b"i686" | b"x86_64", b"linux", ..] => Err(TargetSupportError::GlibcRequired),
			[b"i686", b"windows", b"msvc"] => Ok(Self::Windows32),
			[b"x86_64", b"windows", b"msvc"] => Ok(Self::Windows64),
			[b"i686" | b"x86_64", b"windows", ..] => Err(TargetSupportError::MsvcRequired),
			[..] => Err(TargetSupportError::UnsupportedTarget),
		}
	}

	pub const fn clang_target(&self) -> &'static str {
		match self {
			Self::Linux32 => "i686-unknown-linux-gnu",
			Self::Linux64 => "x86_64-unknown-linux-gnu",
			Self::Windows32 => "i686-pc-windows-msvc",
			Self::Windows64 => "x86_64-pc-windows-msvc",
		}
	}

	pub const fn is_32bit(&self) -> bool {
		matches!(self, Self::Linux32 | Self::Windows32)
	}

	pub const fn is_64bit(&self) -> bool {
		matches!(self, Self::Linux64 | Self::Windows64)
	}

	pub const fn is_linux(&self) -> bool {
		matches!(self, Self::Linux32 | Self::Linux64)
	}

	pub const fn is_windows(&self) -> bool {
		matches!(self, Self::Windows32 | Self::Windows64)
	}

	pub(crate) const fn layout(&self) -> layout::TargetLayout {
		match self {
			Self::Linux32 => layout::TargetLayout {
				pointer_width: 4,
				c_long_width: 4,
				int64_align: 4,
			},
			Self::Linux64 => layout::TargetLayout {
				pointer_width: 8,
				c_long_width: 8,
				int64_align: 8,
			},
			Self::Windows32 => layout::TargetLayout {
				pointer_width: 4,
				c_long_width: 4,
				int64_align: 8,
			},
			Self::Windows64 => layout::TargetLayout {
				pointer_width: 8,
				c_long_width: 4,
				int64_align: 8,
			},
		}
	}

	pub const fn short_name(&self) -> &'static str {
		match self {
			Self::Linux32 => "linux_32",
			Self::Linux64 => "linux_64",
			Self::Windows32 => "windows_32",
			Self::Windows64 => "windows_64",
		}
	}
}

#[derive(Debug, Clone, thiserror::Error)]
pub enum TargetSupportError {
	#[error("Source SDK 2013 requires MSVC for Windows targets")]
	MsvcRequired,

	#[error("Source SDK 2013 requires glibc for Linux targets")]
	GlibcRequired,

	#[error("Unsupported target")]
	UnsupportedTarget,
}

fn add_generated_binding_attributes(syntax: &mut File) {
	let lint_allowances: Attribute = parse_quote! {
		#![allow(
			clippy::all,
			ambiguous_glob_reexports,
			non_snake_case,
			non_camel_case_types,
			non_upper_case_globals,
			unsafe_op_in_unsafe_fn,
			unused_imports,
			unused_qualifications
		)]
	};

	syntax.attrs.insert(0, lint_allowances);
}

fn add_generated_file_headers(files: &mut BTreeMap<PathBuf, String>) {
	for source in files.values_mut() {
		source.insert_str(0, GENERATED_FILE_HEADER);
	}
}

fn consolidate_extern_c_blocks(items: &mut Vec<Item>) -> Result<(), BindgenError> {
	let mut consolidated = None::<syn::ItemForeignMod>;
	let mut retained = Vec::with_capacity(items.len());

	for item in std::mem::take(items) {
		let Item::ForeignMod(mut foreign) = item else {
			retained.push(item);

			continue;
		};

		if foreign
			.abi
			.name
			.as_ref()
			.is_some_and(|name| name.value() != "C")
		{
			retained.push(Item::ForeignMod(foreign));

			continue;
		}

		if !foreign.attrs.is_empty() {
			return Err(BindgenError::AttributedExternCBlock);
		}

		if let Some(existing) = &mut consolidated {
			if existing.unsafety.is_some() != foreign.unsafety.is_some() {
				return Err(BindgenError::MixedExternCUnsafety);
			}

			existing.items.append(&mut foreign.items);
		} else {
			consolidated = Some(foreign);
		}
	}

	if let Some(mut foreign) = consolidated {
		foreign
			.items
			.sort_by_cached_key(ItemOrder::foreign_item_order);
		retained.push(Item::ForeignMod(foreign));
	}

	*items = retained;

	Ok(())
}

fn binding_builder(
	header: &str,
	clang_args: &[String],
	provenance: ProvenanceCollector,
	external_opaque: &[String],
	include_vtable_probes: bool,
) -> bindgen::Builder {
	let mut builder = bindgen::builder()
		.header_contents(BRIDGE_FILE, header)
		.clang_args(clang_args)
		.parse_callbacks(Box::new(provenance))
		.opaque_type("std::.*")
		.opaque_type("KeyValues")
		// These bridge declarations stand in for troublesome SDK definitions and
		// intentionally expose identity only, never a fabricated object layout.
		.opaque_type("^bf_(read|write)$")
		// Interfaces are invoked through vtables. Free SDK symbols would require
		// import/static libraries that plugins do not link.
		.blocklist_function(".*")
		.blocklist_var(".*")
		.layout_tests(true)
		.generate_inline_functions(true)
		.vtable_generation(true)
		.rust_target(RustTarget::stable(98, 1).expect("the requested Rust target is supported"))
		.allowlist_recursively(true);

	for root in ROOT_TYPES {
		builder = builder.allowlist_type(root);
	}

	for pattern in external_opaque {
		builder = builder.opaque_type(pattern);
	}

	if include_vtable_probes {
		builder = builder.allowlist_type("^__crys_vtable_.*");
	}

	builder
}

fn bindgen_record_name_map(
	records: &RecordIndex,
	provenance: &ProvenanceIndex,
	generated_types: &BTreeSet<String>,
) -> Result<BTreeMap<String, String>, BindgenError> {
	let mut mapped = BTreeMap::new();

	for (qualified_name, record) in records.records() {
		// Bindgen names a record by joining its enclosing scopes with `_`, and
		// reports the record's own spelling as its original name. Both must
		// agree. A same-named record in another scope (for example another
		// template's `Iterator_t`) is never a match.
		let flattened_name = bindgen_flattened_cpp_name(qualified_name);

		let candidates = provenance
			.records()
			.filter(|item| {
				matches!(
					item.kind,
					GeneratedItemKind::Struct | GeneratedItemKind::Union
				) && generated_types.contains(&item.final_name)
			})
			.filter(|item| item.final_name == flattened_name)
			.filter(|item| {
				item.original_name.as_deref().is_some_and(|name| {
					cpp_names_equal(name, qualified_name) || cpp_names_equal(name, &record.name)
				})
			})
			.map(|item| item.final_name.clone())
			.collect::<BTreeSet<_>>();

		match candidates.len() {
			0 => {}

			1 => {
				mapped.insert(
					qualified_name.clone(),
					candidates
						.into_iter()
						.next()
						.expect("the length was checked"),
				);
			}

			_ => {
				return Err(BindgenError::AmbiguousRecordMapping {
					record: qualified_name.clone(),
					candidates: candidates.into_iter().collect(),
				});
			}
		}
	}

	Ok(mapped)
}

fn bindgen_flattened_cpp_name(qualified_name: &str) -> String {
	qualified_name
		.trim_start_matches("::")
		.split("::")
		.collect::<Vec<_>>()
		.join("_")
		.chars()
		.map(|character| {
			if character.is_ascii_alphanumeric() || character == '_' {
				character
			} else {
				'_'
			}
		})
		.collect::<String>()
}

fn clang_arguments(sdk_src: &Path, target: SupportedTarget) -> Vec<String> {
	let mut arguments = vec![
		"-x".to_owned(),
		"c++".to_owned(),
		"-std=c++17".to_owned(),
		// Probes name private nested classes, such as the network-variable
		// wrappers `CNetworkVarEmbedded` declares. Access control never affects
		// layout, so every pass parses without it.
		"-fno-access-control".to_owned(),
		// The game headers trip these hundreds of times per pass, burying any
		// real diagnostic. Neither affects declarations or layouts.
		"-Wno-inconsistent-missing-override".to_owned(),
		"-Wno-null-dereference".to_owned(),
		format!("-I{}", sdk_src.display()),
		format!("-I{}", sdk_src.join("public").display()),
		format!("-I{}", sdk_src.join("public").join("mathlib").display()),
		format!("-I{}", sdk_src.join("public").join("tier0").display()),
		format!("-I{}", sdk_src.join("public").join("tier1").display()),
		format!("-I{}", sdk_src.join("game").join("server").display()),
		format!("-I{}", sdk_src.join("game").join("shared").display()),
		// Last, so it cannot shadow the directories above: `iclient.h` includes
		// `userid.h` from here.
		format!("-I{}", sdk_src.join("common").display()),
	];

	if target.is_windows() {
		arguments.extend([
			"-DCOMPILER_MSVC".to_owned(),
			"-D_CRT_USE_BUILTIN_OFFSETOF".to_owned(),
			"-fms-compatibility".to_owned(),
			"-fms-extensions".to_owned(),
		]);

		if target.is_64bit() {
			arguments.push("-DCOMPILER_MSVC64".to_owned());
		}
	} else {
		arguments.extend([
			"-DCOMPILER_GCC".to_owned(),
			"-DGNUC".to_owned(),
			"-DPOSIX".to_owned(),
			"-DLINUX".to_owned(),
			"-D_LINUX".to_owned(),
			// Legacy template bodies are irrelevant to declarations/layouts and are
			// rejected by current Clang unless their parsing is delayed.
			"-fdelayed-template-parsing".to_owned(),
		]);
	}

	arguments.push(format!("--target={}", target.clang_target()));
	arguments
}

