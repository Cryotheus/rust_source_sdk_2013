fn bindgen_flattened_cpp_name(qualified_name: &str) -> String {
	qualified_name
		.trim_start_matches("::")
		.split("::")
		.collect::<Vec<_>>()
		.join("_")
		.chars()
		.map(|character| {
			if character.is_ascii_alphanumeric() || character == '_' {
				character
			} else {
				'_'
			}
		})
		.collect::<String>()
}

fn bindgen_record_name_map(
	records: &RecordIndex,
	provenance: &ProvenanceIndex,
	generated_types: &BTreeSet<String>,
) -> Result<BTreeMap<String, String>, BindgenError> {
	let mut mapped = BTreeMap::new();

	for (qualified_name, record) in records.records() {
		// Bindgen names a record by joining its enclosing scopes with `_`, and
		// reports the record's own spelling as its original name. Both must
		// agree. A same-named record in another scope (for example another
		// template's `Iterator_t`) is never a match.
		let flattened_name = bindgen_flattened_cpp_name(qualified_name);

		let candidates = provenance
			.records()
			.filter(|item| {
				matches!(
					item.kind,
					GeneratedItemKind::Struct | GeneratedItemKind::Union
				) && generated_types.contains(&item.final_name)
			})
			.filter(|item| item.final_name == flattened_name)
			.filter(|item| {
				item.original_name.as_deref().is_some_and(|name| {
					cpp_names_equal(name, qualified_name) || cpp_names_equal(name, &record.name)
				})
			})
			.map(|item| item.final_name.clone())
			.collect::<BTreeSet<_>>();

		match candidates.len() {
			0 => {}

			1 => {
				mapped.insert(
					qualified_name.clone(),
					candidates
						.into_iter()
						.next()
						.expect("the length was checked"),
				);
			}

			_ => {
				return Err(BindgenError::AmbiguousRecordMapping {
					record: qualified_name.clone(),
					candidates: candidates.into_iter().collect(),
				});
			}
		}
	}

	Ok(mapped)
}

fn binding_builder(
	header: &str,
	clang_args: &[String],
	provenance: ProvenanceCollector,
	external_opaque: &[String],
	include_vtable_probes: bool,
) -> bindgen::Builder {
	let mut builder = bindgen::builder()
		.header_contents(BRIDGE_FILE, header)
		.clang_args(clang_args)
		.parse_callbacks(Box::new(provenance))
		.opaque_type("std::.*")
		.opaque_type("KeyValues")
		// These bridge declarations stand in for troublesome SDK definitions and
		// intentionally expose identity only, never a fabricated object layout.
		.opaque_type("^bf_(read|write)$")
		// Interfaces are invoked through vtables. Free SDK symbols would require
		// import/static libraries that plugins do not link.
		.blocklist_function(".*")
		.blocklist_var(".*")
		.layout_tests(true)
		.generate_inline_functions(true)
		.vtable_generation(true)
		.allowlist_file(".*[/\\\\]tf_player(_shared)?\\.h")
		.rust_target(RustTarget::stable(98, 1).expect("the requested Rust target is supported"))
		.allowlist_recursively(true);

	for root in ROOT_TYPES {
		builder = builder.allowlist_type(root);
	}

	for pattern in external_opaque {
		builder = builder.opaque_type(pattern);
	}

	if include_vtable_probes {
		builder = builder.allowlist_type("^__crys_vtable_.*");
	}

	builder
}

