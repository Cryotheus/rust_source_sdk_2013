fn inline_generated_tree(files: &BTreeMap<PathBuf, String>) -> Result<File, syn::Error> {
	fn inline_file(
		file: &mut File,
		directory: &Path,
		files: &BTreeMap<PathBuf, String>,
	) -> Result<(), syn::Error> {
		let mut rendered = Vec::with_capacity(file.items.len());

		for item in std::mem::take(&mut file.items) {
			match item {
				Item::Mod(mut module) if module.content.is_none() => {
					let child_directory = directory.join(module.ident.to_string());
					let child_path = child_directory.join("mod.rs");

					let Some(source) = files.get(&child_path) else {
						return Err(syn::Error::new(
							module.ident.span(),
							format!("generated module tree is missing {child_path:?}"),
						));
					};

					let mut child = syn::parse_file(source)?;

					inline_file(&mut child, &child_directory, files)?;

					for mut attribute in child.attrs {
						attribute.style = syn::AttrStyle::Outer;
						module.attrs.push(attribute);
					}

					module.content = Some((syn::token::Brace::default(), child.items));
					module.semi = None;

					rendered.push(Item::Mod(module));
				}
				Item::Macro(include) if include.mac.path.is_ident("include") => {
					let relative = syn::parse2::<syn::LitStr>(include.mac.tokens.clone())?.value();
					let included_path = directory.join(relative);

					let Some(source) = files.get(&included_path) else {
						return Err(syn::Error::new_spanned(
							include,
							format!("generated module tree is missing {included_path:?}"),
						));
					};

					let mut included = syn::parse_file(source)?;

					inline_file(&mut included, directory, files)?;
					rendered.extend(included.items);
				}

				item => rendered.push(item),
			}
		}

		file.items = rendered;

		Ok(())
	}

	let root_source = files
		.get(Path::new("mod.rs"))
		.expect("generated bindings always contain mod.rs");
	let mut root = syn::parse_file(root_source)?;
	inline_file(&mut root, Path::new(""), files)?;
	Ok(root)
}

/// Whether `name` is exactly one vtable pointer: a struct holding only
/// `vtable_`, or only a `_base` which is itself such an interface.
///
/// A class such as `class NetworkVar_m_fog : public fogparams_t` also has a
/// single `_base` field, but that base carries data and must keep it.
fn is_one_pointer_interface(syntax: &File, name: &str) -> bool {
	fn check(syntax: &File, name: &str, visiting: &mut BTreeSet<String>) -> bool {
		if !visiting.insert(name.to_owned()) {
			return false;
		}

		syntax.items.iter().any(|item| {
			let Item::Struct(item) = item else {
				return false;
			};

			if item.ident != name || !item.generics.params.is_empty() {
				return false;
			}

			let Fields::Named(fields) = &item.fields else {
				return false;
			};
			let mut fields = fields.named.iter();

			let (Some(field), None) = (fields.next(), fields.next()) else {
				return false;
			};

			match field.ident.as_ref().map(ToString::to_string).as_deref() {
				Some("vtable_") => true,
				Some("_base") => {
					plain_type_name(&field.ty).is_some_and(|base| check(syntax, &base, visiting))
				}
				_ => false,
			}
		})
	}

	check(syntax, name, &mut BTreeSet::new())
}

fn plain_type_name(type_: &syn::Type) -> Option<String> {
	let syn::Type::Path(path) = type_ else {
		return None;
	};

	if path.qself.is_some() || path.path.segments.len() != 1 {
		return None;
	}

	let segment = path.path.segments.first()?;
	segment
		.arguments
		.is_none()
		.then(|| segment.ident.to_string())
}

fn namespaced_module(module: &ModulePath) -> Result<ModulePath, ModulePathError> {
	let mut path = PathBuf::from(MODULE_NAMESPACE);
	path.extend(module.segments());
	ModulePath::from_header_path(path)
}

fn mapped_probe_field_names(
	probe: &VtableProbe,
	generated_name: &str,
) -> Result<Vec<String>, BindgenError> {
	let probe_key = probe
		.stem
		.strip_prefix("__crys_vtable_")
		.unwrap_or(&probe.stem);
	let prefix = format!("{probe_key}_");
	probe
		.field_names
		.iter()
		.map(|field| {
			let suffix =
				field
					.strip_prefix(&prefix)
					.ok_or_else(|| BindgenError::InvalidProbeFieldName {
						probe: probe.stem.clone(),
						field: field.clone(),
					})?;
			Ok(format!("{generated_name}_{suffix}"))
		})
		.collect()
}

fn order_generated_items(syntax: &mut File) -> Result<(), BindgenError> {
	order_module_items(&mut syntax.items)
}

fn order_module_items(items: &mut Vec<Item>) -> Result<(), BindgenError> {
	for item in items.iter_mut() {
		match item {
			Item::Impl(item) => item.items.sort_by_cached_key(ItemOrder::impl_item_order),

			Item::Mod(item) => {
				if let Some((_, items)) = &mut item.content {
					order_module_items(items)?;
				}
			}

			_ => {}
		}
	}

	consolidate_extern_c_blocks(items)?;
	items.sort_by_cached_key(ItemOrder::module_item_order);
	Ok(())
}

fn reject_directly_linked_symbols(syntax: &File) -> Result<(), BindgenError> {
	#[derive(Default)]
	struct DirectSymbolVisitor {
		found: bool,
	}

	impl<'ast> Visit<'ast> for DirectSymbolVisitor {
		fn visit_attribute(&mut self, attribute: &'ast Attribute) {
			self.found |= attribute.path().is_ident("link_name");
			syn::visit::visit_attribute(self, attribute);
		}

		fn visit_foreign_item(&mut self, item: &'ast ForeignItem) {
			self.found |= matches!(item, ForeignItem::Fn(_) | ForeignItem::Static(_));
			syn::visit::visit_foreign_item(self, item);
		}
	}

	let mut visitor = DirectSymbolVisitor::default();

	visitor.visit_file(syntax);

	if visitor.found {
		return Err(BindgenError::DirectlyLinkedSymbol);
	}

	Ok(())
}

fn render_partitioned_modules(
	syntax: File,
	provenance: &ProvenanceIndex,
	support_module: ModulePath,
) -> Result<BTreeMap<PathBuf, String>, BindgenError> {
	let mut tree = ModuleTree::new();
	let mut module_paths = Vec::new();

	for (source_module, mut file) in partition_file(syntax, provenance, support_module) {
		let module = namespaced_module(&source_module)?;
		let depth = module.as_segments().len();
		let parent = std::iter::repeat_n("super", depth)
			.collect::<Vec<_>>()
			.join("::");
		let import: Item = syn::parse_str(&format!(
			"#[allow(unused_imports)] use {parent}::__bindgen_prelude::*;"
		))?;
		file.items.insert(0, import);
		tree.insert(module.clone(), file)?;
		module_paths.push(module);
	}

	let mut files = tree.render();
	let root_source = files
		.remove(Path::new("mod.rs"))
		.ok_or(BindgenError::MissingRootModule)?;
	let mut root = syn::parse_file(&root_source)?;
	add_generated_binding_attributes(&mut root);

	let reexports = module_paths
		.iter()
		.map(|module| {
			let path = module.segments().collect::<Vec<_>>().join("::");
			format!("pub use super::{path}::*;")
		})
		.collect::<Vec<_>>()
		.join("\n");
	let prelude: Item = syn::parse_str(&format!(
		"#[doc(hidden)] #[allow(ambiguous_glob_reexports, unused_imports)] mod __bindgen_prelude {{ {reexports} }}"
	))?;
	root.items.push(prelude);
	root.items.push(parse_quote! {
		#[allow(ambiguous_glob_reexports, unused_imports)]
		pub use self::__bindgen_prelude::*;
	});
	root.items.sort_by_cached_key(ItemOrder::module_item_order);
	files.insert(PathBuf::from("mod.rs"), prettyplease::unparse(&root));
	add_generated_file_headers(&mut files);
	Ok(files)
}

/// The C++ record whose bindgen name prefixes `generated_name` before an
/// underscore, as bindgen spells a record's nested declarations. The longest
/// unambiguous prefix wins.
fn enclosing_cpp_record(records: &RecordIndex, generated_name: &str) -> Option<String> {
	let mut by_flattened_name = BTreeMap::<String, BTreeSet<&String>>::new();

	for qualified_name in records.records().keys() {
		by_flattened_name
			.entry(bindgen_flattened_cpp_name(qualified_name))
			.or_default()
			.insert(qualified_name);
	}

	by_flattened_name
		.into_iter()
		.filter(|(flattened, _)| {
			generated_name
				.strip_prefix(flattened.as_str())
				.is_some_and(|rest| rest.starts_with('_'))
		})
		.filter(|(_, qualified_names)| qualified_names.len() == 1)
		.max_by_key(|(flattened, _)| flattened.len())
		.and_then(|(_, qualified_names)| qualified_names.into_iter().next().cloned())
}

/// The C++ name of a generated struct or union declared at global scope,
/// where bindgen's name and the C++ spelling agree.
fn top_level_cpp_name(provenance: &ProvenanceIndex, generated_name: &str) -> Option<String> {
	provenance
		.records()
		.filter(|item| {
			matches!(
				item.kind,
				GeneratedItemKind::Struct | GeneratedItemKind::Union
			)
		})
		.find(|item| {
			item.final_name == generated_name
				&& item.original_name.as_deref() == Some(generated_name)
		})
		.map(|item| item.final_name.clone())
}

fn validate_root_names(syntax: &File) -> Result<(), BindgenError> {
	for item in &syntax.items {
		let name = match item {
			Item::Struct(item) => Some(item.ident.to_string()),
			Item::Union(item) => Some(item.ident.to_string()),
			Item::Enum(item) => Some(item.ident.to_string()),
			Item::Type(item) => Some(item.ident.to_string()),
			Item::Const(item) if item.ident != "_" => Some(item.ident.to_string()),
			Item::Static(item) => Some(item.ident.to_string()),
			Item::Fn(item) => Some(item.sig.ident.to_string()),
			_ => None,
		};
		if name
			.as_deref()
			.is_some_and(|name| name == MODULE_NAMESPACE || name == "__bindgen_prelude")
		{
			return Err(BindgenError::RootNameCollision {
				name: name.expect("checked above"),
			});
		}
	}
	Ok(())
}

