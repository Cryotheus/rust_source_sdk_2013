#[derive(Debug)]
pub struct GeneratedBindings {
	files: BTreeMap<PathBuf, String>,
	included_files: Vec<PathBuf>,
}

impl GeneratedBindings {
	/// All generated files, keyed by their path relative to the output folder.
	pub fn files(&self) -> &BTreeMap<PathBuf, String> {
		&self.files
	}

	/// Headers observed while parsing the final translation unit.
	pub fn included_files(&self) -> &[PathBuf] {
		&self.included_files
	}

	/// Returns the root `mod.rs` for the split, filesystem-backed module tree.
	pub fn root_source(&self) -> &str {
		self.files
			.get(Path::new("mod.rs"))
			.map(String::as_str)
			.expect("generated bindings always contain mod.rs")
	}

	/// Renders a self-contained inline module tree as readable Rust source.
	pub fn to_source(&self) -> String {
		let syntax = inline_generated_tree(&self.files)
			.expect("the generated module tree was already parsed and validated");

		format_generated(syntax, false).expect("the generated modules were already formatted")
	}

	/// Returns a self-contained inline module tree as Rust tokens.
	///
	/// [`Self::write`] still emits the same bindings as separate files. Use
	/// [`Self::root_source`] when only that split tree's root `mod.rs` is needed.
	pub fn to_token_stream(&self) -> TokenStream {
		let syntax = inline_generated_tree(&self.files)
			.expect("the generated module tree was already parsed and validated");

		quote::quote!(#syntax)
	}

	/// Writes the split tree and removes stale files owned by an earlier write.
	/// Files not listed in the generator manifest are never removed.
	pub fn write(&self, path: impl AsRef<Path>) -> Result<(), std::io::Error> {
		let root = path.as_ref();

		fs::create_dir_all(root)?;

		let desired = self
			.files
			.keys()
			.map(|path| Ok((generated_path_key(path)?, path)))
			.collect::<Result<BTreeMap<_, _>, std::io::Error>>()?;

		let manifest_path = root.join(GENERATED_FILES_MANIFEST);

		let previous = match fs::read_to_string(&manifest_path) {
			Ok(manifest) => manifest
				.lines()
				.filter(|line| !line.is_empty() && !line.starts_with('#'))
				.map(generated_path_from_key)
				.collect::<Result<Vec<_>, _>>()?,

			Err(error) if error.kind() == std::io::ErrorKind::NotFound => Vec::new(),
			Err(error) => return Err(error),
		};

		for stale in previous {
			if desired.contains_key(&generated_path_key(&stale)?) {
				continue;
			}

			info!("[STALE] {}", stale.display());

			match fs::remove_file(root.join(stale)) {
				Ok(()) => {}
				Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
				Err(error) => return Err(error),
			}
		}

		for (relative, contents) in &self.files {
			let output = root.join(relative);

			if let Some(parent) = output.parent() {
				fs::create_dir_all(parent)?;
			}

			info!("[OUT] {}", output.display());
			fs::write(output, contents)?;
		}

		let mut manifest = String::from(GENERATED_MANIFEST_HEADER);

		manifest.push_str(&desired.keys().cloned().collect::<Vec<_>>().join("\n"));
		manifest.push('\n');
		fs::write(&manifest_path, manifest)?;
		info!("Manifest written: {}", manifest_path.display());

		Ok(())
	}
}

/// All targets supported by this crate as of now.
#[derive(Debug, Clone, Copy, Eq, PartialEq)]
pub enum SupportedTarget {
	/// `i686-unknown-linux-gnu`
	Linux32,

	/// `x86_64-unknown-linux-gnu`
	Linux64,

	/// `i686-pc-windows-msvc`
	Windows32,

	/// `x86_64-pc-windows-msvc`
	Windows64,
}

impl SupportedTarget {
	pub fn from_env() -> anyhow::Result<Self> {
		Self::from_parts(
			&cargo_var("CARGO_CFG_TARGET_ARCH")?,
			&cargo_var("CARGO_CFG_TARGET_OS")?,
			&cargo_var("CARGO_CFG_TARGET_ENV")?,
		)
		.map_err(Into::into)
	}

	pub const fn from_host() -> Result<Self, TargetSupportError> {
		let arch = cfg_select! {
			target_arch = "x86" => "i686",
			target_arch = "x86_64" => "x86_64",
			_ => "",
		};

		let os = cfg_select! {
			target_os = "linux" => "linux",
			target_os = "windows" => "windows",
			_ => "",
		};

		let env = cfg_select! {
			target_env = "msvc" => "msvc",
			target_env = "gnu" => "gnu",
			_ => "",
		};

		Self::from_parts(arch, os, env)
	}

	pub const fn from_parts(arch: &str, os: &str, env: &str) -> Result<Self, TargetSupportError> {
		// HACK: cannot match `str` in `const` yet, so use `as_bytes`.
		match [arch.as_bytes(), os.as_bytes(), env.as_bytes()] {
			[b"i686", b"linux", b"gnu"] => Ok(Self::Linux32),
			[b"x86_64", b"linux", b"gnu"] => Ok(Self::Linux64),
			[b"i686" | b"x86_64", b"linux", ..] => Err(TargetSupportError::GlibcRequired),
			[b"i686", b"windows", b"msvc"] => Ok(Self::Windows32),
			[b"x86_64", b"windows", b"msvc"] => Ok(Self::Windows64),
			[b"i686" | b"x86_64", b"windows", ..] => Err(TargetSupportError::MsvcRequired),
			[..] => Err(TargetSupportError::UnsupportedTarget),
		}
	}

	pub const fn clang_target(&self) -> &'static str {
		match self {
			Self::Linux32 => "i686-unknown-linux-gnu",
			Self::Linux64 => "x86_64-unknown-linux-gnu",
			Self::Windows32 => "i686-pc-windows-msvc",
			Self::Windows64 => "x86_64-pc-windows-msvc",
		}
	}

	pub const fn is_32bit(&self) -> bool {
		matches!(self, Self::Linux32 | Self::Windows32)
	}

	pub const fn is_64bit(&self) -> bool {
		matches!(self, Self::Linux64 | Self::Windows64)
	}

	pub const fn is_linux(&self) -> bool {
		matches!(self, Self::Linux32 | Self::Linux64)
	}

	pub const fn is_windows(&self) -> bool {
		matches!(self, Self::Windows32 | Self::Windows64)
	}

	pub(crate) const fn layout(&self) -> layout::TargetLayout {
		match self {
			Self::Linux32 => layout::TargetLayout {
				pointer_width: 4,
				c_long_width: 4,
				int64_align: 4,
			},

			Self::Linux64 => layout::TargetLayout {
				pointer_width: 8,
				c_long_width: 8,
				int64_align: 8,
			},

			Self::Windows32 => layout::TargetLayout {
				pointer_width: 4,
				c_long_width: 4,
				int64_align: 8,
			},

			Self::Windows64 => layout::TargetLayout {
				pointer_width: 8,
				c_long_width: 4,
				int64_align: 8,
			},
		}
	}

	pub const fn short_name(&self) -> &'static str {
		match self {
			Self::Linux32 => "linux_32",
			Self::Linux64 => "linux_64",
			Self::Windows32 => "windows_32",
			Self::Windows64 => "windows_64",
		}
	}
}

impl FromStr for SupportedTarget {
	type Err = TargetSupportError;

	fn from_str(str: &str) -> Result<Self, Self::Err> {
		let mut split = str.split("-");

		//should use a better error type...
		let arch = split.next().ok_or(TargetSupportError::UnsupportedTarget)?;
		let _vendor = split.next().ok_or(TargetSupportError::UnsupportedTarget)?;
		let os = split.next().ok_or(TargetSupportError::UnsupportedTarget)?;
		let env = split.next().ok_or(TargetSupportError::UnsupportedTarget)?;

		if split.next().is_some() {
			return Err(TargetSupportError::UnsupportedTarget);
		}

		Self::from_parts(arch, os, env)
	}
}

