const SUPPORT_HEADER: &str = "__bindgen/support.rs";

#[derive(Debug)]
pub struct Bindgen {
	sdk_path: PathBuf,
}

impl Bindgen {
	/// Generates bindings for Cargo's current target.
	pub fn generate(self) -> Result<GeneratedBindings, BindgenError> {
		let target = SupportedTarget::from_parts(
			&cargo_var("CARGO_CFG_TARGET_ARCH")?,
			&cargo_var("CARGO_CFG_TARGET_OS")?,
			&cargo_var("CARGO_CFG_TARGET_ENV")?,
		)?;

		self.generate_for(target)
	}

	/// Generates bindings for an explicitly selected target ABI.
	///
	/// Build scripts should prefer this method so the target selecting the C++
	/// ABI is necessarily the same target selecting the output directory.
	pub fn generate_for(self, target: SupportedTarget) -> Result<GeneratedBindings, BindgenError> {
		info!("[STEP] Config");

		let sdk_src = self.sdk_path.join("src");
		let protocol_headers = protobuf::prepare_for_build(&sdk_src)?;
		let mut clang_args = clang_arguments(&sdk_src, target);
		clang_args.push(format!("-I{}", protocol_headers.include_dir.display()));

		let abi = match target {
			SupportedTarget::Linux32 => CppAbi::ItaniumX86,
			SupportedTarget::Linux64 => CppAbi::Itanium,
			SupportedTarget::Windows32 => CppAbi::MsvcX86,
			SupportedTarget::Windows64 => CppAbi::Msvc,
		};

		// The discovery pass determines which transitively reachable types belong
		// to the SDK. Any reachable compiler/toolchain types become opaque in the
		// final pass; unrelated unreachable types are absent altogether.
		let discovery = ProvenanceCollector::new(&sdk_src, [BRIDGE_FILE])
			.with_external_roots([sdk_src.join("thirdparty")]);

		info!("[STEP] Discovery");

		let discovery_bindings =
			binding_builder(BRIDGE_SOURCE, &clang_args, discovery.clone(), &[], false)
				.generate()?;

		let discovery_syntax = syn::parse_file(&discovery_bindings.to_string())?;
		let discovery_index = discovery.index();

		info!("[STEP] Record collection");

		// Bindgen deliberately emits dummy vtable types for several valid C++
		// layouts. Derive complete tables from the same translation unit and feed
		// typed probe structs through bindgen on the final pass.
		let generated_types = discovery_index.generated_type_names();
		let records = collect_records_under_root(BRIDGE_FILE, BRIDGE_SOURCE, &clang_args, &sdk_src)
			.map_err(cpp_vtable_error)?;

		let generated_record_names =
			bindgen_record_name_map(&records, &discovery_index, &generated_types)?;

		let mut layouts = Vec::new();
		let mut opaque_vtables = BTreeMap::new();

		info!("[STEP] Opaque vtable filtering");

		for qualified_name in records.records().keys() {
			let Some(generated_name) = generated_record_names.get(qualified_name) else {
				continue;
			};

			if discovery_index
				.module_for_generated_name(generated_name)
				.is_none()
			{
				opaque_vtables.insert(
					generated_name.clone(),
					"external dependency type; only its identity and layout are retained"
						.to_owned(),
				);

				continue;
			}

			let layout = match records
				.vtable_model(qualified_name, abi)
				.map_err(cpp_vtable_error)?
			{
				VtableModel::NotPolymorphic => continue,
				VtableModel::Modeled(layout) => layout,

				// Bindgen's placeholder vtable (if any) stays in place and is
				// documented, so no slot order is ever guessed.
				VtableModel::Unsupported { reason } => {
					if opaque_vtables
						.insert(generated_name.clone(), reason)
						.is_some()
					{
						return Err(BindgenError::DuplicateVtableTarget {
							target: generated_name.clone(),
						});
					}

					continue;
				}
			};

			layouts.push((generated_name, layout));
		}

		info!("[STEP] Call trait analysis");

		// How a class passed or returned by value crosses the call depends on
		// its special members, which only Clang's semantic analysis knows.
		let call_traits = query_record_call_traits(
			BRIDGE_FILE,
			BRIDGE_SOURCE,
			&clang_args,
			layouts
				.iter()
				.flat_map(|(_, layout)| layout.by_value_records()),
		)
		.map_err(cpp_vtable_error)?;

		let mut probes = Vec::new();
		let mut flattened_interfaces = Vec::new();
		let mut probe_targets = BTreeMap::new();
		let mut expected_vtables = BTreeMap::new();

		info!("[STEP] Render probes");

		for (generated_name, layout) in layouts {
			let probe =
				render_vtable_probe(&records, &layout, &call_traits).map_err(cpp_vtable_error)?;

			let probe_key = probe
				.stem
				.strip_prefix("__crys_vtable_")
				.unwrap_or(&probe.stem)
				.to_owned();

			if probe_targets
				.insert(probe_key.clone(), generated_name.clone())
				.is_some()
			{
				return Err(BindgenError::DuplicateProbeStem { stem: probe_key });
			}

			let expected_fields = mapped_probe_field_names(&probe, generated_name)?;

			if expected_vtables
				.insert(generated_name.clone(), expected_fields)
				.is_some()
				|| opaque_vtables.contains_key(generated_name)
			{
				return Err(BindgenError::DuplicateVtableTarget {
					target: generated_name.clone(),
				});
			}

			if is_one_pointer_interface(&discovery_syntax, generated_name) {
				flattened_interfaces.push(generated_name.clone());
			}

			probes.push(probe);
		}

		for root in ROOT_TYPES {
			if let Some(reason) = opaque_vtables.get(*root) {
				return Err(BindgenError::UnmodeledRootVtable {
					root: (*root).to_owned(),
					reason: reason.clone(),
				});
			}
		}

		let mut final_header = String::from(BRIDGE_SOURCE);

		info!("[STEP] Render final header");

		for probe in &probes {
			final_header.push_str("\n\n");
			final_header.push_str(&probe.source);
		}

		// Bindgen emits nothing at all for an opaque typedef of an anonymous
		// record, such as glibc's `pthread_mutex_t`, so those stay transparent.
		let external_opaque = discovery_index
			.external_opaque_type_patterns_excluding(records.typedef_named_anonymous_records());

		let generated_to_cpp = generated_record_names
			.iter()
			.map(|(cpp_name, generated_name)| (generated_name.clone(), cpp_name.clone()))
			.collect::<BTreeMap<_, _>>();

		let flattened = flattened_interfaces
			.iter()
			.map(String::as_str)
			.collect::<Vec<_>>();

		let expected = probe_targets.keys().cloned().collect::<BTreeSet<_>>();

		// Records whose C++ layout bindgen cannot express, by C++ name, with
		// the first mismatch found. Each pass makes the newly found ones
		// opaque, and an opaque record always matches its layout.
		let mut inexpressible = BTreeMap::<String, String>::new();
		let mut pass = 0usize;

		info!("[STEP] Make inexpressible layouts opaque");

		let (mut syntax, provenance) = loop {
			let mut opaque_patterns = external_opaque.clone();
			pass += 1;

			info!("       Pass: {pass}");

			opaque_patterns.extend(
				inexpressible
					.keys()
					.map(|cpp_name| format!("^{}$", provenance::escape_regex(cpp_name))),
			);

			let provenance = ProvenanceCollector::new(&sdk_src, [BRIDGE_FILE])
				.with_external_roots([sdk_src.join("thirdparty")]);

			let final_bindings = binding_builder(
				&final_header,
				&clang_args,
				provenance.clone(),
				&opaque_patterns,
				!probes.is_empty(),
			)
			.generate()?;

			let mut syntax = syn::parse_file(&final_bindings.to_string())?;

			reject_directly_linked_symbols(&syntax)?;

			let installed =
				transform::install_vtable_probes(&mut syntax, &probe_targets, &flattened)
					.map_err(vtable_transform_error)?;

			let installed_names = installed.keys().cloned().collect::<BTreeSet<_>>();

			if installed_names != expected {
				return Err(BindgenError::MissingVtableProbes {
					expected: expected.difference(&installed_names).cloned().collect(),
				});
			}

			let provenance = provenance.index();

			prune::prune_unreferenced_external_types(&mut syntax, &provenance);
			layout::remove_unreferenced_broken_aliases(&mut syntax);

			let mismatches = layout::find_layout_mismatches(&syntax, target.layout());

			if mismatches.is_empty() {
				break (syntax, provenance);
			}

			let mut progressed = false;

			for (generated_name, reason) in mismatches.clone() {
				let Some(cpp_name) = generated_to_cpp
					.get(&generated_name)
					.cloned()
					.or_else(|| enclosing_cpp_record(&records, &generated_name))
					.or_else(|| top_level_cpp_name(&provenance, &generated_name))
				else {
					return Err(BindgenError::InexpressibleLayout {
						item: generated_name,
						reason,
					});
				};

				if let std::collections::btree_map::Entry::Vacant(entry) =
					inexpressible.entry(cpp_name)
				{
					entry.insert(reason);
					progressed = true;
				}
			}

			if !progressed {
				let (item, reason) = mismatches
					.into_iter()
					.next()
					.expect("the mismatches were not empty");

				return Err(BindgenError::InexpressibleLayout { item, reason });
			}
		};

		let opaque_records = inexpressible
			.iter()
			.filter_map(|(cpp_name, reason)| {
				Some((
					generated_record_names.get(cpp_name)?.clone(),
					reason.clone(),
				))
			})
			.collect::<BTreeMap<_, _>>();

		info!("[STEP] Validate: required classes expressed");

		for required in ["CTFPlayer", "CTFPlayerShared"] {
			if let Some(reason) = opaque_records.get(required) {
				return Err(BindgenError::InexpressibleLayout {
					item: required.to_owned(),
					reason: reason.clone(),
				});
			}
		}

		let opaque_names = opaque_vtables.keys().cloned().collect::<BTreeSet<_>>();

		info!("[STEP] Validate: vtables");
		transform::validate_vtables_against(&syntax, &expected_vtables, &opaque_names)
			.map_err(vtable_transform_error)?;

		info!("[STEP] Doc: opaque vtables");
		transform::document_opaque_vtables(&mut syntax, &opaque_vtables);

		info!("[STEP] Doc: opaque records");
		transform::document_opaque_records(&mut syntax, &opaque_records);

		info!("[STEP] Validate: player records");
		validate_player_records(&syntax)?;

		info!("[STEP] Validate: root names");
		validate_root_names(&syntax)?;
		add_generated_binding_attributes(&mut syntax);

		info!("[STEP] Collect used includes");

		let included_files = provenance
			.included_files()
			.map(Path::to_owned)
			.chain(protocol_headers.inputs)
			.collect();

		info!("[STEP] Render: partitioned modules");

		let support_module = ModulePath::from_header_path(SUPPORT_HEADER)?;
		let files = render_partitioned_modules(syntax, &provenance, support_module)?;

		Ok(GeneratedBindings {
			files,
			included_files,
		})
	}

	pub fn sdk_path(&self) -> &Path {
		&self.sdk_path
	}
}

#[derive(Debug, thiserror::Error)]
pub enum BindgenError {
	#[error(transparent)]
	Protobuf(#[from] protobuf::ProtobufError),

	#[error("C++ record {record:?} maps to multiple generated Rust types: {candidates:?}")]
	AmbiguousRecordMapping {
		record: String,
		candidates: Vec<String>,
	},

	#[error("bindgen: {0}")]
	Bindgen(#[from] bindgen::BindgenError),

	#[error("C++ vtable analysis failed: {0}")]
	CppVtable(String),

	#[error(
		"generated bindings contain a directly linked C++ symbol; expose SDK interfaces through their vtables instead"
	)]
	DirectlyLinkedSymbol,

	#[error("more than one C++ vtable probe has identifier stem {stem:?}")]
	DuplicateProbeStem { stem: String },

	#[error("more than one C++ vtable probe targets generated Rust type {target:?}")]
	DuplicateVtableTarget { target: String },

	#[error("could not format generated Rust bindings: {0}")]
	Format(#[from] FormatError),

	#[error("vtable probe {probe:?} emitted unexpected field name {field:?}")]
	InvalidProbeFieldName { probe: String, field: String },

	#[error("not every generated C++ vtable probe was installed; missing {expected:?}")]
	MissingVtableProbes { expected: Vec<String> },

	#[error("generated module tree did not contain its root module")]
	MissingRootModule,

	#[error(transparent)]
	ModulePath(#[from] ModulePathError),

	#[error(transparent)]
	ModuleTree(#[from] ModuleTreeError),

	#[error("could not parse generated Rust bindings: {0}")]
	Parse(#[from] syn::Error),

	#[error("environment: {0}")]
	RequireVar(#[from] RequireVarError),

	#[error("generated item {name:?} collides with a reserved root module name")]
	RootNameCollision { name: String },

	#[error(transparent)]
	TargetSupport(#[from] TargetSupportError),

	#[error(
		"generated item {item:?} does not match its C++ layout and cannot be made opaque: {reason}"
	)]
	InexpressibleLayout { item: String, reason: String },

	#[error("root type {root:?} has a vtable which cannot be modeled: {reason}")]
	UnmodeledRootVtable { root: String, reason: String },

	#[error("full TF2 player bindings require the generated field {record}::{field}")]
	IncompletePlayerRecord { record: String, field: String },

	#[error("generated vtable transformation failed: {0}")]
	VtableTransform(String),
}

#[derive(Debug)]
#[non_exhaustive]
pub struct Builder {
	pub sdk_path: PathResolutionMethod,
}

impl Builder {
	pub fn new() -> Self {
		Self {
			sdk_path: PathResolutionMethod::new_env("SOURCE_SDK_2013"),
		}
	}

	pub fn build(self) -> Result<Bindgen, BuilderError> {
		Ok(Bindgen {
			sdk_path: self.sdk_path.resolve()?,
		})
	}

	pub fn with_sdk_path(mut self, path: PathBuf) -> Self {
		self.sdk_path = PathResolutionMethod::Provided(path);
		self
	}
}

impl Default for Builder {
	fn default() -> Self {
		Self::new()
	}
}

